// Files for the commit: today's digest, latest.json and the list of available dates.
const cfg = $('Config').first().json;
const { digest } = $('Build digest').first().json;
const MAX_DATES = 180;

let dates = [];
const existing = $input.first()?.json;
// A 404 on the first run is expected: the index doesn't exist yet.
if (existing && !existing.error && typeof existing.data === 'string') {
  try {
    const parsed = JSON.parse(existing.data);
    if (Array.isArray(parsed?.dates)) dates = parsed.dates.filter((d) => /^\d{4}-\d{2}-\d{2}$/.test(d));
  } catch {
    dates = [];
  }
}

dates = [cfg.date, ...dates.filter((d) => d !== cfg.date)].sort().reverse().slice(0, MAX_DATES);

const pretty = (value) => `${JSON.stringify(value, null, 2)}\n`;
const files = [
  { path: `public/digest/${cfg.date}.json`, content: pretty(digest) },
  { path: 'public/digest/latest.json', content: pretty(digest) },
  { path: 'public/digest/index.json', content: pretty({ version: 1, updatedAt: digest.generatedAt, dates }) },
];

const message = [
  `Daily digest ${cfg.date}`,
  '',
  `${digest.items.length} posts picked from ${digest.stats.fetched} by ${cfg.models.score}, ${cfg.models.summary} and ${cfg.models.editor}.`,
  'Generated by the n8n "Pixel Wires - Daily digest" workflow.',
].join('\n');

return [{ json: { files, message } }];
